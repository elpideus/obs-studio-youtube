#!/usr/bin/env python3
"""Regenerate obs-studio-youtube/ from Arch Linux's obs-studio packaging at a given tag.

Usage: tools/update-from-arch.py [ARCH_TAG] [--cache DIR] [--out DIR] [--pkgrel REL]
  ARCH_TAG   e.g. 32.2.2-1 (default: newest tag in Arch's packaging repo)

Arch's PKGBUILD is kept as close to verbatim as possible. The script only:
  - renames the split packages to obs-studio-youtube / obs-studio-youtube-plugin-browser,
    which provide and conflict with obs-studio / obs-studio-plugin-browser;
  - reads the user's own Google OAuth client and passes the YouTube options to cmake;
  - checks that cmake actually enabled the YouTube integration.
Every edit is anchored on exact text and the script stops if an anchor is missing, so a
changed upstream PKGBUILD is noticed instead of silently mis-patched. Review the git diff
after running it.
"""
import argparse
import os
import re
import subprocess
import sys
from pathlib import Path

ARCH_REPO = "https://gitlab.archlinux.org/archlinux/packaging/packages/obs-studio.git"
ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "obs-studio-youtube"

HEADER = """\
# Maintainer: Stefan Cucoranu <elpideus@gmail.com>
#
# Generated by tools/update-from-arch.py from Arch Linux's obs-studio PKGBUILD
# (tag {tag}, https://gitlab.archlinux.org/archlinux/packaging/packages/obs-studio),
# whose maintainers and contributors were:
{credits}
#
# Same OBS Studio, same build options, plus the YouTube account integration (Connect
# Account, Manage Broadcast, chat dock). Distro builds can't ship it because it needs a
# Google OAuth client compiled in; this package builds it with YOUR OWN client:
#   ~/.config/obs-youtube/credentials.env   (YOUTUBE_CLIENTID="..." / YOUTUBE_SECRET="...")
# or the environment variables OBS_YOUTUBE_CLIENTID / OBS_YOUTUBE_SECRET.
# See https://github.com/elpideus/obs-studio-youtube#google-api-client
"""

CREDENTIALS = r'''
_obs_youtube_credentials() {
  # Your own Google OAuth "Desktop app" client. Never commit or share these values.
  YOUTUBE_CLIENTID="${OBS_YOUTUBE_CLIENTID:-}"
  YOUTUBE_SECRET="${OBS_YOUTUBE_SECRET:-}"
  local _file="${OBS_YOUTUBE_CREDENTIALS:-${XDG_CONFIG_HOME:-$HOME/.config}/obs-youtube/credentials.env}"
  if [[ ( -z $YOUTUBE_CLIENTID || -z $YOUTUBE_SECRET ) && -r $_file ]]; then
    # Parsed, not sourced: only the two KEY="value" lines are read.
    YOUTUBE_CLIENTID=$(sed -n 's/^YOUTUBE_CLIENTID="\{0,1\}\([^"]*\)"\{0,1\}[[:space:]]*$/\1/p' "$_file")
    YOUTUBE_SECRET=$(sed -n 's/^YOUTUBE_SECRET="\{0,1\}\([^"]*\)"\{0,1\}[[:space:]]*$/\1/p' "$_file")
  fi
  if [[ $YOUTUBE_CLIENTID != *.apps.googleusercontent.com || -z $YOUTUBE_SECRET ]]; then
    error "No Google OAuth client found for the YouTube integration."
    plainerr "Create one (see https://github.com/elpideus/obs-studio-youtube#google-api-client),"
    plainerr "then put it in $_file or export OBS_YOUTUBE_CLIENTID / OBS_YOUTUBE_SECRET."
    return 1
  fi
}
'''


def fail(msg):
    sys.exit(f"update-from-arch: {msg}")


def sub_once(text, old, new, what):
    n = text.count(old)
    if n != 1:
        fail(f"anchor for '{what}' found {n} times (expected 1); Arch's PKGBUILD changed, update this script")
    return text.replace(old, new)


def git(*args, cwd=None):
    return subprocess.run(["git", *args], cwd=cwd, check=True, capture_output=True, text=True).stdout


def transform(pkgbuild, tag, pkgrel=None):
    credits = [l for l in pkgbuild.splitlines() if re.match(r"# (Maintainer|Contributor):", l)]
    if not credits:
        fail("no Maintainer/Contributor lines found")
    body = "\n".join(l for l in pkgbuild.splitlines() if not re.match(r"# (Maintainer|Contributor):", l))
    body = body.lstrip("\n")
    credits = "\n".join("#   " + re.sub(r"^# (Maintainer|Contributor):\s*", r"\1: ", l) for l in credits)

    t = HEADER.format(tag=tag, credits=credits) + "\n" + body + "\n"

    t = sub_once(t, "pkgbase=obs-studio\n", "pkgbase=obs-studio-youtube\n", "pkgbase")
    if pkgrel:
        if not re.fullmatch(r"[0-9]+(\.[0-9]+)?", pkgrel):
            fail(f"invalid pkgrel {pkgrel!r}")
        t, n = re.subn(r"^pkgrel=.*$", f"pkgrel={pkgrel}", t, count=1, flags=re.M)
        if n != 1:
            fail("pkgrel line not found")
    t = sub_once(t, "pkgname=('obs-studio' 'obs-studio-plugin-browser')\n",
                 "pkgname=('obs-studio-youtube' 'obs-studio-youtube-plugin-browser')\n", "pkgname")
    t = re.sub(r'^pkgdesc="([^"]*)"$',
               r'pkgdesc="\1 (with YouTube account integration, using your own Google API client)"',
               t, count=1, flags=re.M)

    # Credentials helper before build(), loaded and passed to cmake inside it.
    t = sub_once(t, "\nbuild() {\n", "\n" + CREDENTIALS.strip("\n") + "\n\nbuild() {\n"
                 "  local YOUTUBE_CLIENTID YOUTUBE_SECRET\n  _obs_youtube_credentials || return 1\n\n", "build()")
    t = sub_once(t, "  local cmake_options=(\n",
                 "  local cmake_options=(\n"
                 "    -DYOUTUBE_CLIENTID=\"$YOUTUBE_CLIENTID\"\n"
                 "    -DYOUTUBE_SECRET=\"$YOUTUBE_SECRET\"\n"
                 "    -DYOUTUBE_CLIENTID_HASH=0\n"
                 "    -DYOUTUBE_SECRET_HASH=0\n", "cmake_options")
    t = sub_once(t, '  cmake "${cmake_options[@]}"\n',
                 '  cmake "${cmake_options[@]}"\n'
                 "  # feature-youtube.cmake silently skips the integration if anything is missing\n"
                 "  grep -qs -- '-DYOUTUBE_ENABLED' build/frontend/CMakeFiles/obs-studio.dir/flags.make build/build.ninja \\\n"
                 "    || { error \"cmake did not enable the YouTube integration\"; return 1; }\n", "cmake call")

    # Split packages: rename, provide and conflict with the repo packages.
    t = sub_once(t, "package_obs-studio() {\n",
                 "package_obs-studio-youtube() {\n"
                 "  provides=(\"obs-studio=$pkgver\")\n"
                 "  conflicts=('obs-studio')\n", "package_obs-studio")
    t = sub_once(t, "'obs-studio-plugin-browser: CEF-based browser plugin'",
                 "'obs-studio-youtube-plugin-browser: CEF-based browser plugin'", "browser optdepend")
    t = sub_once(t, "package_obs-studio-plugin-browser() {\n",
                 "package_obs-studio-youtube-plugin-browser() {\n"
                 "  provides=(\"obs-studio-plugin-browser=$pkgver\")\n"
                 "  conflicts=('obs-studio-plugin-browser')\n", "package_obs-studio-plugin-browser")
    m = re.search(r"^(  depends=\([^)]*)'obs-studio'([^)]*\))$", t, flags=re.M)
    if not m:
        fail("browser plugin depends on 'obs-studio' not found")
    t = t[:m.start()] + m.group(1) + "\"obs-studio-youtube=${pkgver}-${pkgrel}\"" + m.group(2) + t[m.end():]
    return t


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("tag", nargs="?")
    ap.add_argument("--cache", default=os.path.expanduser("~/.cache/obs-studio-youtube/arch-obs-studio"))
    ap.add_argument("--out", type=Path, default=OUT, help="package directory to write (default: obs-studio-youtube/)")
    ap.add_argument("--pkgrel", help="override pkgrel, e.g. 1.1 for a local rebuild against updated libraries")
    a = ap.parse_args()
    out = a.out

    cache = Path(a.cache)
    if (cache / ".git").is_dir():
        git("fetch", "-q", "--tags", "--force", "origin", cwd=cache)
    else:
        cache.parent.mkdir(parents=True, exist_ok=True)
        git("clone", "-q", ARCH_REPO, str(cache))
    tag = a.tag or git("tag", "--sort=-v:refname", cwd=cache).split()[0]

    files = git("ls-tree", "--name-only", tag, cwd=cache).split()
    if "PKGBUILD" not in files:
        fail(f"tag {tag} has no PKGBUILD")
    out.mkdir(parents=True, exist_ok=True)
    for old in out.glob("*.patch"):
        old.unlink()
    for name in files:
        if name.endswith(".patch"):
            (out / name).write_bytes(subprocess.run(["git", "show", f"{tag}:{name}"], cwd=cache,
                                                    check=True, capture_output=True).stdout)
    pkgbuild = git("show", f"{tag}:PKGBUILD", cwd=cache)
    (out / "PKGBUILD").write_text(transform(pkgbuild, tag, a.pkgrel))
    (out / ".arch-tag").write_text(tag + "\n")

    srcinfo = subprocess.run(["makepkg", "--printsrcinfo"], cwd=out, check=True, capture_output=True, text=True)
    (out / ".SRCINFO").write_text(srcinfo.stdout)
    print(f"{out} regenerated from Arch tag {tag}")


if __name__ == "__main__":
    main()
